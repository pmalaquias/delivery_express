package com.pmalaquias.deliveryexpress.data.models.enums

/**
 * Enum class representing different types of vehicles.
 *
 * @property Car Represents a car.
 * @property PickupTruck Represents a pickup truck.
 * @property Truck Represents a truck.
 * @property Motorcycle Represents a motorcycle.
 * @property Bicycle Represents a bicycle.
 * @property Other Represents any other type of vehicle not listed above.
 */
enum class VehicleType {
    Car,
    PickupTruck,
    Truck,
    Motorcycle,
    Bicycle,
    Other
}