package com.pmalaquias.deliveryexpress.data.models.enums

/**
 * Enum class representing different colors of vehicles.
 *
 * @property White Represents a white vehicle.
 * @property Gray Represents a gray vehicle.
 * @property Red Represents a red vehicle.
 * @property Blue Represents a blue vehicle.
 * @property Green Represents a green vehicle.
 * @property Black Represents a black vehicle.
 * @property Yellow Represents a yellow vehicle.
 * @property Other Represents any other color of vehicle not listed above.
 */
enum class VehicleColor {
    White,
    Gray,
    Red,
    Blue,
    Green,
    Black,
    Yellow,
    Other
}