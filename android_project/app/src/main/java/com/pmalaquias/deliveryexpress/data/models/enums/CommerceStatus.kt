package com.pmalaquias.deliveryexpress.data.models.enums

/**
 * Enum class representing different statuses of a commerce.
 *
 * @property OPEN Represents a commerce status where the commerce is open.
 * @property CLOSED Represents a commerce status where the commerce is closed.
 * @property MAINTENANCE Represents a commerce status where the commerce is under maintenance.
 */
enum class CommerceStatus {
    OPEN,
    CLOSED,
    MAINTENANCE
}