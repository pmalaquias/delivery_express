package com.pmalaquias.deliveryexpress.data.models.enums

/**
 * Enum class representing different statuses of a delivery person.
 *
 * @property AVAILABLE Represents a delivery person status where the delivery person is available.
 * @property BUSY Represents a delivery person status where the delivery person is busy.
 * @property OFFLINE Represents a delivery person status where the delivery person is offline.
 */
enum class DeliveryPersonStatus {
    AVAILABLE,
    BUSY,
    OFFLINE
}
